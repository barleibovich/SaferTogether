        private static void AddTexturedPlane(Transform parent, string name, string texturePath, Vector3 position, Vector2 size, string materialName, bool centerVisiblePixels, bool preserveAspect)
        {
            Texture2D texture = LoadTexture(texturePath);
            Vector2 renderSize = preserveAspect ? SizeWithTextureAspect(texture, size) : size;
            GameObject quad = GameObject.CreatePrimitive(PrimitiveType.Quad);
            quad.name = name;
            quad.transform.SetParent(parent, false);
            quad.transform.localPosition = position + (centerVisiblePixels ? VisiblePixelOffset(texture, renderSize) : Vector3.zero);
            quad.transform.localRotation = Quaternion.identity;
            quad.transform.localScale = new Vector3(renderSize.x, renderSize.y, 1f);

            Renderer renderer = quad.GetComponent<Renderer>();
            renderer.sharedMaterial = MaterialForTexture(materialName, texture);

            Collider collider = quad.GetComponent<Collider>();
            if (collider != null)
            {
                UnityEngine.Object.DestroyImmediate(collider);
            }

        }

        private static Vector2 SizeWithTextureAspect(Texture2D texture, Vector2 requestedSize)
        {
            if (texture == null || texture.width <= 0 || texture.height <= 0)
            {
                return requestedSize;
            }

            return new Vector2(requestedSize.x, requestedSize.x * texture.height / texture.width);
        }

        private static Vector3 VisiblePixelOffset(Texture2D texture, Vector2 renderSize)
        {
            if (texture == null)
            {
                return Vector3.zero;
            }

            Color32[] pixels = texture.GetPixels32();
            int minX = texture.width;
            int minY = texture.height;
            int maxX = -1;
            int maxY = -1;

            // Aligns layers by the center of their non-transparent artwork, so PNG padding does not move clothes/accessories.
            for (int y = 0; y < texture.height; y++)
            {
                int rowStart = y * texture.width;

                for (int x = 0; x < texture.width; x++)
                {
                    if (pixels[rowStart + x].a <= 8)
                    {
                        continue;
                    }

                    minX = Mathf.Min(minX, x);
                    minY = Mathf.Min(minY, y);
                    maxX = Mathf.Max(maxX, x);
                    maxY = Mathf.Max(maxY, y);
                }
            }

            if (maxX < minX || maxY < minY)
            {
                return Vector3.zero;
            }

            float centerX = (minX + maxX + 1f) * 0.5f / texture.width;
            float centerY = (minY + maxY + 1f) * 0.5f / texture.height;

            return new Vector3(
                (0.5f - centerX) * renderSize.x,
                (0.5f - centerY) * renderSize.y,
                0
            );
        }

        private static Texture2D LoadTexture(string assetPath)
        {
            TextureImporter importer = AssetImporter.GetAtPath(assetPath) as TextureImporter;

            if (importer == null)
            {
                throw new FileNotFoundException("Avatar image asset was not imported: " + assetPath);
            }

            importer.textureType = TextureImporterType.Default;
            importer.alphaIsTransparency = true;
            importer.isReadable = true;
            importer.mipmapEnabled = false;
            importer.npotScale = TextureImporterNPOTScale.None;
            importer.wrapMode = TextureWrapMode.Clamp;
            importer.SaveAndReimport();

            Texture2D texture = AssetDatabase.LoadAssetAtPath<Texture2D>(assetPath);

            if (texture == null)
            {
                throw new FileNotFoundException("Avatar image asset could not be loaded: " + assetPath);
            }

            return texture;
        }

        private static Material MaterialForTexture(string name, Texture texture)
        {
            string path = MaterialPathRoot + "/" + Sanitize(name) + ".mat";
            Material material = AssetDatabase.LoadAssetAtPath<Material>(path);
            Shader shader = Shader.Find("Sprites/Default")
                ?? Shader.Find("Unlit/Transparent")
                ?? Shader.Find("Standard");

            if (material == null)
            {
                material = new Material(shader)
                {
                    name = Sanitize(name)
                };
                AssetDatabase.CreateAsset(material, path);
            }
            else
            {
                material.shader = shader;
            }

            material.SetTexture("_MainTex", texture);
            material.mainTexture = texture;
            material.color = Color.white;
            EditorUtility.SetDirty(material);
            return material;
        }

        private static string ColoredSourcePath(string species, string category, string folder, string filePrefix, string colorName)
        {
            string folderAssetPath = SourceImageAssetRoot + "/" + species + "/" + category + "/" + folder;
            string exactPath = folderAssetPath + "/" + filePrefix + " " + colorName + ".png";

            if (File.Exists(AssetPathToFullPath(exactPath)))
            {
                return exactPath;
            }

            string folderPath = AssetPathToFullPath(folderAssetPath);
            string[] matches = Directory.GetFiles(folderPath, "*" + colorName + ".png", SearchOption.TopDirectoryOnly);

            if (matches.Length == 0)
            {
                throw new FileNotFoundException("Could not find " + colorName + " image in " + folderAssetPath);
            }

            return FullPathToAssetPath(matches[0]);
        }

