        private static string Sanitize(string value)
        {
            char[] chars = value.ToLowerInvariant().ToCharArray();

            for (int index = 0; index < chars.Length; index++)
            {
                char c = chars[index];
                if ((c < 'a' || c > 'z') && (c < '0' || c > '9') && c != '-' && c != '_')
                {
                    chars[index] = '-';
                }
            }

            return new string(chars);
        }

