        [InitializeOnLoadMethod]
        private static void AutoGenerateOnce()
        {
            if (SessionState.GetBool(AutoGenerationSessionKey, false))
            {
                return;
            }

            SessionState.SetBool(AutoGenerationSessionKey, true);
            EditorApplication.delayCall += () =>
            {
                if (!File.Exists(AvatarPrefabPath(CharacterAvatarOptions.Male)) && Directory.Exists(ExternalAvatarSourcePath()))
                {
                    GenerateAssets(false);
                    InstallBuilderInOpenScene();
                }
            };
        }

