        public static void GenerateAssets(bool overwrite)
        {
            if (overwrite)
            {
                DeleteGeneratedCatalogFolders();
            }

            EnsureFolders();
            ImportSourceImages();
            CreateAvatarPrefabs(overwrite);
            CreateClothingPrefabs("shirts", "Shirts", ShirtSources, AvatarAttachmentSlot.Shirt, new Vector2(1.48f, 1.48f), overwrite);
            CreatePantsPrefabs(overwrite);
            CreateClothingPrefabs("shoes", "Shoes", ShoeSources, AvatarAttachmentSlot.Shoes, new Vector2(1.08f, 1.08f), overwrite);
            CreateAccessoryPrefabs(overwrite);

            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
        }

        public static void InstallBuilderInOpenScene()
        {
            Scene scene = SceneManager.GetActiveScene();

            if (!scene.IsValid())
            {
                return;
            }

            AvatarBuilder builder = UnityEngine.Object.FindAnyObjectByType<AvatarBuilder>();

            if (builder == null)
            {
                GameObject builderObject = new GameObject("AvatarBuilder");
                builder = builderObject.AddComponent<AvatarBuilder>();
            }

            Transform previewRoot = builder.transform.Find("AvatarPreviewRoot");

            if (previewRoot == null)
            {
                previewRoot = new GameObject("AvatarPreviewRoot").transform;
                previewRoot.SetParent(builder.transform, false);
            }

            builder.avatarRoot = previewRoot;
            builder.resourcesRoot = "GeneratedAvatarBuilder";
            builder.instantiateAvatarPrefabs = true;
            builder.maleAvatar = LoadAvatar(CharacterAvatarOptions.Male);
            builder.femaleAvatar = LoadAvatar(CharacterAvatarOptions.Female);
            builder.dragonAvatar = LoadAvatar(CharacterAvatarOptions.Dragon);
            builder.devilAvatar = LoadAvatar(CharacterAvatarOptions.Devil);
            builder.accessoryPrefabs = BuildAccessoryCatalog();
            builder.shirtPrefabs = BuildColorCatalog("Shirts", AvatarAttachmentSlot.Shirt, CharacterAvatarOptions.Tops);
            builder.pantsPrefabs = BuildColorCatalog("Pants", AvatarAttachmentSlot.Pants, CharacterAvatarOptions.Bottoms);
            builder.shoePrefabs = BuildColorCatalog("Shoes", AvatarAttachmentSlot.Shoes, CharacterAvatarOptions.Shoes);

            EditorUtility.SetDirty(builder);

            if (!string.IsNullOrEmpty(scene.path))
            {
                EditorSceneManager.MarkSceneDirty(scene);
                EditorSceneManager.SaveScene(scene);
            }
        }

        public static void InstallBuilderInRuntimeScene()
        {
            EnsureRuntimeScene();
            EditorSceneManager.OpenScene(RuntimeScenePath, OpenSceneMode.Single);
            InstallBuilderInOpenScene();
        }

        private static void EnsureRuntimeScene()
        {
            if (File.Exists(RuntimeScenePath))
            {
                return;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(RuntimeScenePath));
            Scene scene = EditorSceneManager.NewScene(NewSceneSetup.DefaultGameObjects, NewSceneMode.Single);
            EditorSceneManager.SaveScene(scene, RuntimeScenePath);
            AssetDatabase.Refresh();
        }

        private static void CreateAvatarPrefabs(bool overwrite)
        {
            foreach (string species in CharacterAvatarOptions.Species)
            {
                string fileName = char.ToUpperInvariant(species[0]) + species.Substring(1) + ".png";
                string texturePath = SourceImageAssetRoot + "/" + species + "/" + fileName;
                GameObject root = AvatarRoot(species);
                root.transform.localPosition = AvatarRootPositionFor(species);
                root.transform.localScale = AvatarRootScaleFor(species);
                AddTexturedPlane(root.transform, "Base", texturePath, AvatarLayerPosition + new Vector3(0, 0, 0.03f), AvatarLayerSize, "avatar-" + species, false, true);
                AddAttachmentSet(root, ProfileFor(species));
                SavePrefab(root, AvatarPrefabPath(species), overwrite);
            }
        }

        private static void CreateClothingPrefabs(string sourceCategory, string prefabCategory, StyleSource[] sources, AvatarAttachmentSlot slot, Vector2 size, bool overwrite)
        {
            foreach (string species in CharacterAvatarOptions.Species)
            {
                if (!UsesClothing(species))
                {
                    continue;
                }

                foreach (StyleSource source in sources)
                {
                    for (int index = 0; index < ClothingColorIds.Length; index++)
                    {
                        string colorId = ClothingColorIds[index];
                        string colorName = ClothingColorNames[index];
                        string texturePath = ColoredSourcePath(species, sourceCategory, source.folder, source.filePrefix, colorName);
                        SaveImagePart(species, prefabCategory, source.id, colorId, slot, texturePath, PartSize(species, prefabCategory, source.id, size), overwrite);
                    }
                }
            }
        }

        private static void CreatePantsPrefabs(bool overwrite)
        {
            CreateClothingPrefabs("pants", "Pants", PantsSources, AvatarAttachmentSlot.Pants, new Vector2(1.3f, 1.3f), overwrite);

            foreach (string species in CharacterAvatarOptions.Species)
            {
                if (!UsesClothing(species))
                {
                    continue;
                }

                string texturePath = SourceImageAssetRoot + "/" + species + "/pants/Jeans/Jeans.png";
                SaveImagePart(species, "Pants", CharacterAvatarOptions.Jeans, CharacterAvatarOptions.Denim, AvatarAttachmentSlot.Pants, texturePath, PartSize(species, "Pants", CharacterAvatarOptions.Jeans, new Vector2(1.28f, 1.28f)), overwrite);
            }
        }

        private static void CreateAccessoryPrefabs(bool overwrite)
        {
            foreach (string species in CharacterAvatarOptions.Species)
            {
                foreach (AccessorySource source in AccessorySources)
                {
                    string texturePath = SourceImageAssetRoot + "/" + species + "/accesories/" + source.fileName + ".png";
                    GameObject root = PartRoot(source.id);
                    ApplyAccessoryPrefabTransform(root, species, source.id);
                    AddTexturedPlane(root.transform, source.id, texturePath, AccessoryOffset(species, source.id), AccessorySize(species, source.id), "accessory-" + species + "-" + source.id, true, true);
                    SavePrefab(root, PartPrefabPath("Accessories", species, source.id), overwrite);
                }
            }
        }

