        private static void CreateShirtPrefabs(bool overwrite)
        {
            foreach (string id in CharacterAvatarOptions.Tops)
            {
                GameObject root = PartRoot(id);
                Material mat = Material("part-shirt-" + id, new Color32(102, 217, 239, 255));
                Primitive("Chest", PrimitiveType.Cube, root.transform, Vector3.zero, id == CharacterAvatarOptions.Dress ? new Vector3(1.05f, 1.12f, 0.24f) : new Vector3(0.92f, 0.66f, 0.24f), mat);

                if (id != CharacterAvatarOptions.Vest && id != CharacterAvatarOptions.Armor)
                {
                    Primitive("Left Sleeve", PrimitiveType.Capsule, root.transform, new Vector3(-0.52f, -0.04f, 0), new Vector3(0.16f, 0.46f, 0.16f), mat, new Vector3(0, 0, -14));
                    Primitive("Right Sleeve", PrimitiveType.Capsule, root.transform, new Vector3(0.52f, -0.04f, 0), new Vector3(0.16f, 0.46f, 0.16f), mat, new Vector3(0, 0, 14));
                }

                if (id == CharacterAvatarOptions.Hoodie || id == CharacterAvatarOptions.Sweatshirt)
                {
                    Primitive("Pocket", PrimitiveType.Cube, root.transform, new Vector3(0, -0.23f, -0.14f), new Vector3(0.52f, 0.16f, 0.05f), Material("part-shirt-shadow", new Color32(43, 92, 114, 255)));
                }

                if (id == CharacterAvatarOptions.Armor)
                {
                    Primitive("Plate", PrimitiveType.Sphere, root.transform, new Vector3(0, 0.02f, -0.14f), new Vector3(0.52f, 0.52f, 0.08f), Material("armor-metal", new Color32(188, 198, 211, 255)));
                }

                SavePrefab(root, PartPrefabPath("Shirts", id), overwrite);
            }
        }

