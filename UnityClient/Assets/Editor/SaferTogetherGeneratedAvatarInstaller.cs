        private const string RootPath = "Assets/Resources/GeneratedAvatarBuilder";
        private const string RuntimeScenePath = "Assets/Scenes/RuntimeAvatar.unity";
        private const string AvatarPathRoot = RootPath + "/Avatars";
        private const string PartPathRoot = RootPath + "/Parts";
        private const string MaterialPathRoot = RootPath + "/Materials";
        private const string AutoGenerationSessionKey = "SaferTogether.GeneratedAvatarBuilder.AutoGenerated";

        [InitializeOnLoadMethod]
        private static void AutoGenerateOnce()
        {
            if (SessionState.GetBool(AutoGenerationSessionKey, false))
            {
                return;
            }

            SessionState.SetBool(AutoGenerationSessionKey, true);
            EditorApplication.delayCall += () =>
            {
                if (!File.Exists(AvatarPrefabPath(CharacterAvatarOptions.Human)))
                {
                    GenerateAssets(false);
                    InstallBuilderInOpenScene();
                }
            };
        }

        [MenuItem("SaferTogether/Generate 3D Avatar Prefabs")]
        public static void GenerateAndInstall()
        {
            GenerateAssets(true);
            InstallBuilderInRuntimeScene();
        }

        public static void GenerateAssets(bool overwrite)
        {
            EnsureFolders();
            Material skin = Material("skin", new Color32(218, 154, 105, 255));
            Material skinLight = Material("skin-light", new Color32(255, 214, 185, 255));
            Material hair = Material("hair-brown", new Color32(91, 55, 36, 255));
            Material green = Material("dragon-green", new Color32(55, 163, 74, 255));
            Material gold = Material("gold", new Color32(240, 180, 72, 255));
            Material red = Material("devil-red", new Color32(196, 67, 58, 255));
            Material white = Material("warm-white", new Color32(245, 238, 219, 255));
            Material bear = Material("bear-fur", new Color32(170, 103, 45, 255));
            Material elephant = Material("elephant-blue", new Color32(112, 159, 185, 255));
            Material dark = Material("dark-leather", new Color32(45, 35, 30, 255));

            SaveAvatar(CharacterAvatarOptions.Human, CreateHumanAvatar(skin, hair, dark), overwrite);
            SaveAvatar(CharacterAvatarOptions.Dragon, CreateDragonAvatar(green, gold, dark), overwrite);
            SaveAvatar(CharacterAvatarOptions.Bear, CreateBearAvatar(bear, skinLight, dark), overwrite);
            SaveAvatar(CharacterAvatarOptions.Elephant, CreateElephantAvatar(elephant, gold, dark), overwrite);
            SaveAvatar(CharacterAvatarOptions.Devil, CreateDevilAvatar(red, dark, gold), overwrite);
            SaveAvatar(CharacterAvatarOptions.Angel, CreateAngelAvatar(skinLight, white, gold), overwrite);

            CreateShirtPrefabs(overwrite);
            CreatePantsPrefabs(overwrite);
            CreateShoePrefabs(overwrite);
            CreateAccessoryPrefabs(overwrite);

            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
        }

        public static void InstallBuilderInOpenScene()
        {
            Scene scene = SceneManager.GetActiveScene();

            if (!scene.IsValid())
            {
                return;
            }

            AvatarBuilder builder = Object.FindAnyObjectByType<AvatarBuilder>();

            if (builder == null)
            {
                GameObject builderObject = new GameObject("AvatarBuilder");
                builder = builderObject.AddComponent<AvatarBuilder>();
            }

            Transform previewRoot = builder.transform.Find("AvatarPreviewRoot");

            if (previewRoot == null)
            {
                previewRoot = new GameObject("AvatarPreviewRoot").transform;
                previewRoot.SetParent(builder.transform, false);
            }

            builder.avatarRoot = previewRoot;
            builder.resourcesRoot = "GeneratedAvatarBuilder";
            builder.instantiateAvatarPrefabs = true;
            builder.humanAvatar = LoadAvatar(CharacterAvatarOptions.Human);
            builder.dragonAvatar = LoadAvatar(CharacterAvatarOptions.Dragon);
            builder.bearAvatar = LoadAvatar(CharacterAvatarOptions.Bear);
            builder.elephantAvatar = LoadAvatar(CharacterAvatarOptions.Elephant);
            builder.devilAvatar = LoadAvatar(CharacterAvatarOptions.Devil);
            builder.angelAvatar = LoadAvatar(CharacterAvatarOptions.Angel);
            builder.accessoryPrefabs = BuildAccessoryCatalog();
            builder.shirtPrefabs = BuildCatalog("Shirts", AvatarAttachmentSlot.Shirt, CharacterAvatarOptions.Tops);
            builder.pantsPrefabs = BuildCatalog("Pants", AvatarAttachmentSlot.Pants, CharacterAvatarOptions.Bottoms);
            builder.shoePrefabs = BuildShoeCatalog();

            EditorUtility.SetDirty(builder);

            if (!string.IsNullOrEmpty(scene.path))
            {
                EditorSceneManager.MarkSceneDirty(scene);
                EditorSceneManager.SaveScene(scene);
            }
        }

        public static void InstallBuilderInRuntimeScene()
        {
            EnsureRuntimeScene();
            EditorSceneManager.OpenScene(RuntimeScenePath, OpenSceneMode.Single);
            InstallBuilderInOpenScene();
        }

        private static void EnsureRuntimeScene()
        {
            if (File.Exists(RuntimeScenePath))
            {
                return;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(RuntimeScenePath));
            Scene scene = EditorSceneManager.NewScene(NewSceneSetup.DefaultGameObjects, NewSceneMode.Single);
            EditorSceneManager.SaveScene(scene, RuntimeScenePath);
            AssetDatabase.Refresh();
        }

