        private static Transform Point(string name, Transform parent, Vector3 position)
        {
            Transform point = new GameObject(name).transform;
            point.SetParent(parent, false);
            point.localPosition = position;
            return point;
        }

        private static GameObject AvatarRoot(string name)
        {
            GameObject root = new GameObject(name);
            root.transform.localScale = Vector3.one;
            return root;
        }

        private static GameObject PartRoot(string name)
        {
            return new GameObject(name);
        }

        private static GameObject Primitive(string name, PrimitiveType type, Transform parent, Vector3 position, Vector3 scale, Material material, Vector3? rotation = null)
        {
            GameObject primitive = GameObject.CreatePrimitive(type);
            primitive.name = name;
            primitive.transform.SetParent(parent, false);
            primitive.transform.localPosition = position;
            primitive.transform.localRotation = Quaternion.Euler(rotation ?? Vector3.zero);
            primitive.transform.localScale = scale;

            Renderer renderer = primitive.GetComponent<Renderer>();
            if (renderer != null)
            {
                renderer.sharedMaterial = material;
            }

            Collider collider = primitive.GetComponent<Collider>();
            if (collider != null)
            {
                Object.DestroyImmediate(collider);
            }

            return primitive;
        }

        private static void SavePrefab(GameObject root, string path, bool overwrite)
        {
            if (!overwrite && File.Exists(path))
            {
                Object.DestroyImmediate(root);
                return;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(path));
            PrefabUtility.SaveAsPrefabAsset(root, path);
            Object.DestroyImmediate(root);
        }

        private static AvatarPartPrefab[] BuildCatalog(string category, AvatarAttachmentSlot slot, string[] ids)
        {
            AvatarPartPrefab[] result = new AvatarPartPrefab[ids.Length];

            for (int index = 0; index < ids.Length; index++)
            {
                result[index] = new AvatarPartPrefab
                {
                    id = ids[index],
                    slot = slot,
                    prefab = LoadPart(category, ids[index])
                };
            }

            return result;
        }

