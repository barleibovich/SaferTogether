        private static void ImportSourceImages()
        {
            string sourcePath = ExternalAvatarSourcePath();

            if (!Directory.Exists(sourcePath))
            {
                throw new DirectoryNotFoundException("Missing avatar source folder: " + sourcePath);
            }

            DeleteAssetIfExists(SourceImageAssetRoot);

            string destinationPath = AssetPathToFullPath(SourceImageAssetRoot);
            Directory.CreateDirectory(destinationPath);

            foreach (string file in Directory.GetFiles(sourcePath, "*.png", SearchOption.AllDirectories))
            {
                string relative = file.Substring(sourcePath.Length).TrimStart(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
                string destinationFile = Path.Combine(destinationPath, relative);
                Directory.CreateDirectory(Path.GetDirectoryName(destinationFile));
                File.Copy(file, destinationFile, true);
            }

            AssetDatabase.Refresh();
        }

        private static void SavePrefab(GameObject root, string path, bool overwrite)
        {
            if (!overwrite && File.Exists(path))
            {
                UnityEngine.Object.DestroyImmediate(root);
                return;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(path));
            PrefabUtility.SaveAsPrefabAsset(root, path);
            UnityEngine.Object.DestroyImmediate(root);
        }

        private static AvatarPartPrefab[] BuildColorCatalog(string category, AvatarAttachmentSlot slot, string[] ids)
        {
            var result = new List<AvatarPartPrefab>();

            foreach (string species in CharacterAvatarOptions.Species)
            {
                if (!UsesClothing(species))
                {
                    continue;
                }

                foreach (string id in ids)
                {
                    foreach (string color in ColorsForPart(id))
                    {
                        result.Add(new AvatarPartPrefab
                        {
                            species = species,
                            id = id,
                            color = color,
                            slot = slot,
                            prefab = LoadPart(category, species, id + "-" + color)
                        });
                    }
                }
            }

            return result.ToArray();
        }

        private static AvatarPartPrefab[] BuildAccessoryCatalog()
        {
            var result = new List<AvatarPartPrefab>();

            foreach (string species in CharacterAvatarOptions.Species)
            {
                foreach (AccessorySource source in AccessorySources)
                {
                    result.Add(new AvatarPartPrefab
                    {
                        species = species,
                        id = source.id,
                        slot = source.slot,
                        prefab = LoadPart("Accessories", species, source.id)
                    });
                }
            }

            return result.ToArray();
        }

