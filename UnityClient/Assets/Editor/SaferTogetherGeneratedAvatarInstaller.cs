            AvatarProfile profile = ProfileFor(species);
            Vector3 attachmentScale = AttachmentScaleFor(profile, slot);
            return new Vector2(
                DivideByScale(AvatarLayerSize.x, attachmentScale.x),
                DivideByScale(AvatarLayerSize.y, attachmentScale.y)
            );
        }

